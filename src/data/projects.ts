export function getPublishedProjects(): Project[] {
  return projects.filter((p) => p.published).sort((a, b) => a.order - b.order);
}

export function getFeaturedProjects(): Project[] {
  return getPublishedProjects().filter((p) => p.featured);
}

export function getProjectBySlug(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug && p.published);
}

export function getAdjacentProject(slug: string): Project | undefined {
  const list = getPublishedProjects();
  const idx = list.findIndex((p) => p.slug === slug);
  if (idx === -1) return undefined;
  return list[(idx + 1) % list.length];
}
